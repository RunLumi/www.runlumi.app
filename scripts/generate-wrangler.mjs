// Generates wrangler.jsonc from infra/workspace.manifest.mjs.
//   node scripts/generate-wrangler.mjs          write wrangler.jsonc
//   node scripts/generate-wrangler.mjs --check  exit 1 if wrangler.jsonc is out of date
//   node scripts/generate-wrangler.mjs --plan   print (never run) the staging provisioning commands
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { MISSING_ID, manifest } from "../infra/workspace.manifest.mjs";

const indent = (text, pad) => text.split("\n").map((line) => (line ? pad + line : line)).join("\n");
const comment = (text, pad) => text.split("\n").map((line) => `${pad}// ${line}`).join("\n");
const json = (value) => JSON.stringify(value);

function vars(entries, pad) {
  return Object.entries(entries).map(([key, entry]) => `${entry.comment ? `${comment(entry.comment, pad)}\n` : ""}${pad}${json(key)}: ${json(entry.value)}`).join(",\n");
}
function d1(list, pad) {
  return list.map((db) => [
    `${pad}{`,
    `${pad}  "binding": ${json(db.binding)},`,
    `${pad}  "database_name": ${json(db.name)},`,
    `${pad}  "database_id": ${json(db.id ?? MISSING_ID)}${db.migrations ? "," : ""}`,
    ...(db.migrations ? [`${pad}  "migrations_dir": ${json(db.migrations)}`] : []),
    `${pad}}`,
  ].join("\n")).join(",\n");
}
function r2(list, pad) {
  return list.map((bucket) => `${pad}{\n${pad}  "binding": ${json(bucket.binding)},\n${pad}  "bucket_name": ${json(bucket.name)}\n${pad}}`).join(",\n");
}

export function generate(m = manifest) {
  const p = m.production, s = m.staging;
  const routes = p.routes.map((pattern) => `    {\n      "pattern": ${json(pattern)},\n      "zone_name": ${json(p.zone)}\n    }`).join(",\n");
  const staging = [
    `    "staging": {`,
    `      // R-12: lumi-workspace-*-staging resources in APAC (${s.location}). No runlumi.app`,
    `      // routes and no crons, so staging never answers the production domain or`,
    `      // posts to Lark or webhooks. Finance and HRM stay off.`,
    `      "name": ${json(s.name)},`,
    `      "workers_dev": true,`,
    `      "routes": [],`,
    `      "vars": {`,
    vars(s.vars, "        "),
    `      },`,
    `      "triggers": {`,
    `        "crons": []`,
    `      },`,
    `      "d1_databases": [`,
    d1(s.d1, "        "),
    `      ],`,
    `      "r2_buckets": [`,
    r2(s.r2, "        "),
    `      ]`,
    `    }`,
  ].join("\n");
  return [
    `// Generated by scripts/generate-wrangler.mjs from infra/workspace.manifest.mjs.`,
    `// Do not edit by hand: change the manifest and run the generator.`,
    `{`,
    `  "$schema": ${json(m.schema)},`,
    `  "name": ${json(p.name)},`,
    `  "main": ${json(m.main)},`,
    `  "compatibility_date": ${json(m.compatibility_date)},`,
    `  "compatibility_flags": ${json(m.compatibility_flags).replaceAll(",", ", ")},`,
    `  "vars": {`,
    vars(p.vars, "    "),
    `  },`,
    `  "routes": [`,
    routes,
    `  ],`,
    `  "assets": {`,
    `    "binding": ${json(m.assets.binding)},`,
    `    "directory": ${json(m.assets.directory)}`,
    `  },`,
    comment(p.crons.comment, "  "),
    `  "triggers": {`,
    `    "crons": ${json(p.crons.schedules).replaceAll('","', '", "')}`,
    `  },`,
    `  "observability": {`,
    `    "enabled": ${json(m.observability.enabled)}`,
    `  },`,
    `  "d1_databases": [`,
    d1(p.d1, "    "),
    `  ],`,
    `  "r2_buckets": [`,
    r2(p.r2, "    "),
    `  ],`,
    `  "env": {`,
    staging,
    `  }`,
    `}`,
    ``,
  ].join("\n");
}

/** Commands the founder runs once to create staging. Printed, never executed. */
export function plan(m = manifest) {
  const s = m.staging;
  return [
    `# Staging provisioning (APAC). Review, then run yourself; paste the D1 IDs into infra/workspace.manifest.mjs.`,
    ...s.d1.map((db) => `npx wrangler d1 create ${db.name} --location ${s.location}`),
    ...s.r2.map((bucket) => `npx wrangler r2 bucket create ${bucket.name} --location ${s.location}`),
    `node scripts/generate-wrangler.mjs`,
    `npx wrangler d1 migrations apply ${s.d1[0].name} --remote --env staging`,
    `# Secrets for staging are set separately with: npx wrangler secret put <NAME> --env staging`,
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = fileURLToPath(new URL("../wrangler.jsonc", import.meta.url));
  if (process.argv.includes("--plan")) console.log(plan());
  else if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== generate()) { console.error("wrangler.jsonc is out of date: run node scripts/generate-wrangler.mjs"); process.exit(1); }
    console.log("wrangler.jsonc matches infra/workspace.manifest.mjs");
  } else { writeFileSync(target, generate()); console.log("wrote wrangler.jsonc"); }
}
