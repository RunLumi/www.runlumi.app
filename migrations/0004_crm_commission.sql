-- Commission: who sells under which terms, who referred a deal, and the
-- payouts finance records by hand. The policy itself is a versioned row in
-- crm_policies ('local-commission'); version 1 is a PROPOSAL (status
-- "proposed"), not an approved payout policy. See docs/crm/COMMISSION.md.

ALTER TABLE crm_opportunities ADD COLUMN referrer_id TEXT;

CREATE TABLE crm_seller_terms (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  seller_type TEXT NOT NULL CHECK (seller_type IN ('partner_seller', 'partner_referral', 'employee', 'none')),
  effective_from TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  created_by TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX crm_seller_terms_user ON crm_seller_terms(user_id, effective_from);

-- Recorded after money was actually paid outside the CRM; never computed.
CREATE TABLE crm_commission_payouts (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL,
  period TEXT NOT NULL,
  amount_vnd INTEGER NOT NULL CHECK (amount_vnd >= -1000000000 AND amount_vnd <= 1000000000),
  policy_id TEXT NOT NULL REFERENCES crm_policies(id),
  evidence TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  recorded_by TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX crm_commission_payouts_user ON crm_commission_payouts(user_id, period);

